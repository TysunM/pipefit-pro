// The printed nameplate's pictures
// -------------------------------
// Writes src/print/brand.ts: the app icon's P and the light wordmark, the
// same files the header draws from, as base64 for the nameplate that heads a
// printed record (src/print/nameplate.ts). Run it after either picture
// changes; nameplate.test.ts fails until it has been.
//
//   node tools/brand.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const png = (path) => {
  const b = readFileSync(path);
  if (b.toString('latin1', 1, 4) !== 'PNG') throw new Error(`${path} is not a PNG`);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), png: b.toString('base64') };
};
const p = png('assets/wordmark-p.png');
const mark = png('assets/wordmark-light.png');
const one = (name, what, x) => `/** ${what} */\nexport const ${name} = { w: ${x.w}, h: ${x.h}, png: '${x.png}' } as const;\n`;
writeFileSync(
  'src/print/brand.ts',
  '// Generated by tools/brand.mjs from assets/wordmark-p.png and assets/wordmark-light.png. Do not edit; run the tool.\n\n' +
    one('BRAND_P', "The app icon's P, the nameplate's first letter.", p) +
    '\n' +
    one('BRAND_MARK', '"ipeFit Pro" in dark steel and copper, for a light plate on paper.', mark)
);
console.log('brand.ts:', p.w, 'x', p.h, 'and', mark.w, 'x', mark.h);
